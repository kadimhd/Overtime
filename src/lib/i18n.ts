export type Dict = typeof ar;

const dicts: Record<Locale, Dict> = { ar, en };

export function t(locale: Locale): Dict {
  return dicts[locale];
}

/** Localized status label, falling back to the raw value. */
export function statusLabel(d: Dict, status: string): string {
  const key = `st${status}` as keyof Dict;
  return (d[key] as string | undefined) ?? status;
}

export function catName(locale: Locale, c: { nameAr: string; nameEn: string }) {
  return locale === "ar" ? c.nameAr : c.nameEn;
}

export function catDesc(locale: Locale, c: { descAr: string; descEn: string }) {
  return locale === "ar" ? c.descAr : c.descEn;
}
